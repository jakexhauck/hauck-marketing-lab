// Builds what the Hauck Brain connector serves to the Grok Bots: the reference
// guides and every client's vault notes, as one generated TypeScript module
// inside the app. No behaviour rules: Jake writes each bot's instructions in
// Grok himself (2026-10-26).
//
// Runs as the first step of the command-center build, so every push to main
// (a vault edit, a guide edit) reaches the bots on the next deploy. Also run it
// by hand after editing anything here: `node agency/grok-bots/build.mjs`.
import { readFileSync, writeFileSync, readdirSync, existsSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, "..", "..");
const out = join(root, "apps", "command-center", "functions", "lib", "grokBundle.generated.ts");

// get_guide names -> repo paths. broll-prompts is a copy of the ai-broll-ad skill's
// reference/prompts.md (the skill is not in git); refresh it when the skill changes.
// The fulfillment SOP is not here: the app
// renders it from src/lib/sopChecklists.ts at runtime, so it cannot drift.
const GUIDES = {
  ogilvy: "projects/agent-runner/agents/copy/ogilvy.md",
  copywriting: "projects/agent-runner/agents/copy/copywriting.md",
  "copy-frameworks": "projects/agent-runner/agents/copy/copy-frameworks.md",
  "copy-editing": "projects/agent-runner/agents/copy/copy-editing.md",
  "stop-slop": "projects/agent-runner/agents/copy/stop-slop.md",
  "broll-prompts": "agency/grok-bots/guides/broll-prompts.md",
  "past-scripts": "agency/grok-bots/guides/past-scripts.md",
};

// No em dashes reach a bot (Jake's rule), plus vault-only noise (lesson ids, chat
// ids, comments). The dashes are built from char codes so this file holds none.
const EM = String.fromCharCode(0x2014);
const EN = String.fromCharCode(0x2013);
const clean = (text) =>
  text
    .replace(/\r\n/g, "\n")
    .replace(/<!--[\s\S]*?-->/g, "")
    .replace(new RegExp(`^(#+ .*?)\\s*${EM}\\s*`, "gm"), "$1: ")
    .replace(new RegExp(`\\s*${EM}\\s*`, "g"), ", ")
    .replaceAll(EN, "-")
    .replace(/ \^l-[0-9a-f]+/g, "")
    .replace(/, chat [0-9a-f]+\)/g, ")")
    .replace(/\n{3,}/g, "\n\n")
    .trim();

const read = (rel) => clean(readFileSync(join(root, rel), "utf8"));

// A vault note's body: no frontmatter, no own title, no bare "## Lessons" header.
const note = (path) =>
  existsSync(path)
    ? clean(readFileSync(path, "utf8"))
        .replace(/^---\n[\s\S]*?\n---\n/, "")
        .replace(/^# .*\n/m, "")
        .replace(/^## Lessons\n/m, "")
        .trim()
    : "";

const guides = Object.fromEntries(Object.entries(GUIDES).map(([name, rel]) => [name, read(rel)]));

const vaultDir = join(root, "vault", "Clients");
const vault = {};
for (const name of readdirSync(vaultDir).sort()) {
  const dir = join(vaultDir, name);
  vault[name] = { profile: note(join(dir, "Profile.md")), memory: note(join(dir, "Memory.md")), brain: note(join(dir, "Brain.md")) };
}

const ts = `// GENERATED by agency/grok-bots/build.mjs. Do not edit: edit the sources and rebuild.
export const GROK_GUIDES: Record<string, string> = ${JSON.stringify(guides, null, 1)};
export const GROK_VAULT: Record<string, { profile: string; memory: string; brain: string }> = ${JSON.stringify(vault, null, 1)};
`;
writeFileSync(out, ts);
console.log(`grok bundle: ${Object.keys(guides).length} guides, ${Object.keys(vault).length} clients -> ${out}`);
