// Builds compositions/captions.html: caption cues timed from the
// per-line Parakeet word timestamps. Display text fixes ASR spellings.
import fs from "node:fs";
const here = new URL(".", import.meta.url);
const voStart = [["01",0.6],["02",6.5],["03",13],["04",23],["05",33],["06",45.5],["07",58],["08",68.5],["09",75.8],["10",84.3]];
const fix = (w) =>
  w.replace(/^Hawk/, "Hauck").replace(/^laid/, "lead").replace(/app\.hawkmarketing\.com\.?/i, "app.hauckmarketing.com")
   .replace(/^On,$/, "on,").replace(/^Screen$/, "screen").replace(/^App,$/, "app,");
let out = [];
let n = 0;
for (const [k, base] of voStart) {
  const words = JSON.parse(fs.readFileSync(new URL(`words-${k}.json`, here)));
  let cue = [];
  const flush = (force) => {
    if (!cue.length) return;
    const s = base + cue[0].start;
    const e = base + cue[cue.length - 1].end + 0.25;
    out.push({ s, e, text: cue.map((w) => fix(w.text)).join(" ") });
    cue = [];
  };
  // clauses end at punctuation (min 3 words); long clauses split before a joiner near the middle
  const clauses = [];
  let cur = [];
  words.forEach((w, i) => {
    cur.push(w);
    const end = i === words.length - 1;
    if (end || (/[.?!]$/.test(w.text)) || (/,$/.test(w.text) && cur.length >= 3)) { clauses.push(cur); cur = []; }
  });
  const joiners = new Set(["and", "or", "so", "then", "from", "on", "to"]);
  for (const c of clauses) {
    if (c.length <= 8) { cue = c; flush(); continue; }
    let best = -1, bd = 99;
    c.forEach((w, i) => { if (i >= 3 && i <= c.length - 3 && joiners.has(w.text.toLowerCase())) { const d = Math.abs(i - c.length / 2); if (d < bd) { bd = d; best = i; } } });
    if (best < 0) best = Math.ceil(c.length / 2);
    cue = c.slice(0, best); flush(); cue = c.slice(best); flush();
  }
}
// clamp: each cue ends no later than the next starts
for (let i = 0; i < out.length - 1; i++) out[i].e = Math.min(out[i].e, out[i + 1].s);
// Kokoro says "Hauck" like the brand; keep captions free of em dashes by construction.
const html = out
  .map((c, i) => {
    const t = c.text.replace(/[.,]$/, "").replace(/2014/g, ",").replace("click sign in", "click Sign in").replace(/turn on/i, "Turn on").replace("then allow", "then Allow");
    return `      <div id="cap${String(i + 1).padStart(2, "0")}" class="clip cap" data-start="${c.s.toFixed(2)}" data-duration="${(c.e - c.s).toFixed(2)}" data-track-index="3"><span>${t}</span></div>`;
  })
  .join("\n");
const page = `<!doctype html>
<html>
  <head><meta charset="UTF-8" /></head>
  <body>
    <template>
      <style>
        #cap-root { position: absolute; inset: 0; }
        .cap { position: absolute; left: 0; right: 0; bottom: 56px; display: flex; justify-content: center; }
        .cap span { display: block; max-width: 1500px; padding: 14px 30px; border-radius: 18px; text-align: center;
          background: rgba(8, 24, 21, 0.86); border: 2px solid rgba(77, 187, 131, 0.3);
          font: 700 38px/1.25 Inter, sans-serif; color: #eaf5ef; }
      </style>
      <div id="cap-root" data-composition-id="captions" data-width="1920" data-height="1080">
${html}
      </div>
      <script>
        (function () {
          // generated by .work/build-index.mjs from the voiceover word timings
          const tl = gsap.timeline({ paused: true });
          document.querySelectorAll("#cap-root .cap").forEach((c) => {
            const st = parseFloat(c.getAttribute("data-start"));
            tl.fromTo(c.querySelector("span"), { y: 10, opacity: 0 }, { y: 0, opacity: 1, duration: 0.18, ease: "power2.out" }, st);
          });
          window.__timelines["captions"] = tl;
        })();
      </script>
    </template>
  </body>
</html>
`;
fs.writeFileSync(new URL("../compositions/captions.html", here), page);
console.log(out.length + " cues");
