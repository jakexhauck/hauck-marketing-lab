// Writes functions/lib/grokRoutes.generated.ts: the catalogue of every API
// route, which the Software connector's software_routes serves to the Grok
// Bots. Run after adding or changing a route:
//
//   node scripts/grok-routes.mjs
//
// src/lib/grokRoutes.test.ts fails while the file is behind. The parsing lives
// in functions/lib/grokRoutesParse.ts (node strips its types), so the test and
// this script read the routes the same way.

import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";
import { routesFrom } from "../functions/lib/grokRoutesParse.ts";

const app = join(dirname(fileURLToPath(import.meta.url)), "..");
const apiDir = join(app, "functions", "api");
const out = join(app, "functions", "lib", "grokRoutes.generated.ts");

const files = {};
const walk = (dir) => {
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    const full = join(dir, entry.name);
    if (entry.isDirectory()) walk(full);
    else if (entry.name.endsWith(".ts")) files[relative(apiDir, full).replace(/\\/g, "/")] = readFileSync(full, "utf8");
  }
};
walk(apiDir);

const routes = routesFrom(files);
writeFileSync(
  out,
  `// GENERATED by scripts/grok-routes.mjs from functions/api. Do not edit: run the script.\n` +
    `import type { RouteDoc } from "./grokRoutesParse";\n\n` +
    `export const ROUTES: RouteDoc[] = ${JSON.stringify(routes, null, 1)};\n`,
);
console.log(`grok routes: ${routes.length} routes -> ${relative(app, out)}`);
