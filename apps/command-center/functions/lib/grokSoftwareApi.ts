// The whole Command Center for the Grok Bots (Jake, 2026-10-27: "make sure the
// connector for the software has access to literally the whole software").
//
// software_request calls any route the app serves, the way Jake's own browser
// does: a one-minute session, minted here and never handed out, sent to the
// app's own origin, so the call passes the same middleware, role check and
// handler as his click. /api/admin/* runs as the owner admin; any other /api/*
// runs as the named client's owner, which is their own app.
//
// Nothing is held back by path or method, deletes included, the same call as
// the GHL connector's "Everything" (2026-10-26). What stays is the log: every
// call that is not a GET is an admin_audit_log row `grok:software_request`
// before it is sent, with password, token and secret values hidden in that row.
//
// software_routes is the map: every route, its methods and the comment at the
// top of its file (lib/grokRoutesParse.ts, generated by scripts/grok-routes.mjs).

type Row = Record<string, unknown>;

const METHODS = ["GET", "POST", "PUT", "PATCH", "DELETE"] as const;
type Method = (typeof METHODS)[number];
const TOKEN_SECONDS = 60;
// Some pages do real work behind one click (a client's health, a Claude write).
const TIMEOUT_MS = 55_000;
// What one call may carry up, all files together. A Worker holds them in memory.
export const MAX_UPLOAD_BYTES = 50 * 1024 * 1024;

const text = (v: unknown) => (typeof v === "string" ? v.trim() : "");

export function appMethod(v: unknown): Method {
  const m = typeof v === "string" ? v.toUpperCase() : "GET";
  if (!(METHODS as readonly string[]).includes(m)) throw new Error(`method is one of ${METHODS.join(", ")}`);
  return m as Method;
}

/** A clean app path with :tenantId filled from the client, or an error the bot can act on. */
export function appPath(raw: unknown, client: ClientRef | null): string {
  if (typeof raw !== "string") throw new Error("path is an app path, e.g. /api/admin/clients/:tenantId/mission-control");
  let path = raw.trim();
  if (!path.startsWith("/api/")) throw new Error("path starts with /api/ (see software_routes)");
  if (/[?#]/.test(path)) throw new Error("put the query in query, not in the path");
  if (/[\s\\]|\/\/|(^|\/)\.\.?(\/|$)/.test(path)) throw new Error("path segments are names and ids only");
  // Lowercased: Pages matches routes ignoring case (see api/_middleware.ts).
  const lower = path.toLowerCase();
  if (lower === "/api/grok" || lower.startsWith("/api/grok/")) throw new Error("the Grok connectors are not reached through themselves");
  if (/:tenantId\b|\{tenantId\}/.test(path)) {
    if (!client) throw new Error("this path is per client: pass client");
    path = path.replace(/:tenantId\b|\{tenantId\}/g, client.id);
  }
  const unfilled = path.match(/\/(:\w+|\{\w+\})/);
  if (unfilled) throw new Error(`fill in ${unfilled[1]} in the path`);
  return path;
}

/** The URL on the app's own origin. A path that normalizes into something else is refused. */
export function appUrl(origin: string, path: string, query: unknown): URL {
  const url = new URL(origin + path);
  if (url.origin !== new URL(origin).origin || url.pathname !== path) throw new Error("path must stay on the app");
  if (query !== undefined && query !== null) {
    if (typeof query !== "object" || Array.isArray(query)) throw new Error("query is an object of name: value");
    for (const [k, v] of Object.entries(query as Row)) {
      for (const one of Array.isArray(v) ? v : [v]) {
        if (one !== undefined && one !== null) url.searchParams.append(k, String(one));
      }
    }
  }
  return url;
}

const SECRET_KEY = /password|passcode|secret|token|api_?key|private_?key|credential/i;

function hideSecrets(v: unknown): unknown {
  if (Array.isArray(v)) return v.map(hideSecrets);
  if (v && typeof v === "object") {
    return Object.fromEntries(Object.entries(v as Row).map(([k, x]) => [k, SECRET_KEY.test(k) && x !== null && typeof x !== "object" ? "(hidden)" : hideSecrets(x)]));
  }
  return v;
}

/**
 * A body or query as it goes in the change log: credential values hidden, at
 * any depth. A body sent as a JSON string is read the same way; any other text
 * is not logged at all, since it cannot be checked.
 */
export function forLog(v: unknown): unknown {
  if (v === undefined) return null;
  if (typeof v === "string") {
    try {
      return hideSecrets(JSON.parse(v));
    } catch {
      return "(text body)";
    }
  }
  return hideSecrets(v);
}

/** The app's answer as text for the bot. An error status is an error, with the app's own message. */
export async function readAnswer(method: string, path: string, res: Response): Promise<string> {
  if (res.status >= 300 && res.status < 400) return `${res.status}, redirects to ${res.headers.get("location") ?? "(nowhere)"}`;
  const type = res.headers.get("content-type") ?? "";
  if (res.status >= 400) throw new Error(`${method} ${path} returned ${res.status}: ${(await res.text()).slice(0, 2000)}`);
  if (/json/i.test(type)) {
    const body = await res.text();
    try {
      return JSON.stringify(JSON.parse(body), null, 1);
    } catch {
      return body;
    }
  }
  if (!type || /^text\/|xml|javascript/i.test(type)) {
    const body = await res.text();
    return body || `${res.status}, no body`;
  }
  // The size from the header, never by reading the bytes: a video would sit in memory for nothing.
  const length = res.headers.get("content-length");
  await res.body?.cancel();
  return `${res.status}, a file (${type}${length ? `, ${length} bytes` : ""}). Files open in the app.`;
}

interface FileSpec {
  field: string;
  from: string;
  /** The file, refused once it would take the call past `budget` bytes. */
  load: (budget: number) => Promise<File>;
}

const fileName = (url: string) => decodeURIComponent(new URL(url).pathname.split("/").pop() || "file");

const overCap = () => new Error(`Over ${MAX_UPLOAD_BYTES / 1024 / 1024} MB of files in one call; send fewer or smaller.`);

/**
 * A download's bytes, never more than `budget`: refused up front on its
 * length header, and cut off while streaming when it has none. A Worker has
 * 128 MB; one file read whole past the cap would take the isolate down.
 */
async function readCapped(res: Response, budget: number): Promise<Uint8Array[]> {
  if (Number(res.headers.get("content-length")) > budget) {
    await res.body?.cancel();
    throw overCap();
  }
  if (!res.body) return [];
  const reader = res.body.getReader();
  const chunks: Uint8Array[] = [];
  let total = 0;
  for (;;) {
    const { done, value } = await reader.read();
    if (done) return chunks;
    total += value.byteLength;
    if (total > budget) {
      await reader.cancel();
      throw overCap();
    }
    chunks.push(value);
  }
}

/** The files to upload: each from a Drive file id (the agency's Drive) or an http(s) link. */
function fileSpecs(d: GrokDeps, raw: unknown): FileSpec[] {
  if (raw === undefined || raw === null) return [];
  if (!Array.isArray(raw)) throw new Error("files is a list of { drive_file_id or url, field, name, type }");
  return raw.map((f: Row) => {
    const field = text(f?.field) || "file";
    const name = text(f?.name);
    const type = text(f?.type);
    const driveId = text(f?.drive_file_id);
    const url = text(f?.url);
    if (driveId) {
      return {
        field,
        from: `drive:${driveId}`,
        load: async (budget) => {
          const account = await resolveDriveAccount(d.env);
          const meta = (await getFileMeta(d.env, account, driveId, "id,name,mimeType,size")) as { name?: string; mimeType?: string; size?: string } | null;
          if (!meta) throw new Error(`No Drive file ${driveId}.`);
          if (Number(meta.size) > budget) throw overCap();
          const res = await downloadDriveFile(d.env, account, driveId);
          return new File(await readCapped(res, budget), name || meta.name || driveId, { type: type || meta.mimeType || "application/octet-stream" });
        },
      };
    }
    if (/^https?:\/\//i.test(url)) {
      return {
        field,
        from: url,
        load: async (budget) => {
          const res = await fetch(url, { signal: AbortSignal.timeout(TIMEOUT_MS) });
          if (!res.ok) throw new Error(`Could not fetch ${url} (${res.status}).`);
          return new File(await readCapped(res, budget), name || fileName(url), { type: type || res.headers.get("content-type") || "application/octet-stream" });
        },
      };
    }
    throw new Error("each file needs drive_file_id or an http(s) url");
  });
}

/** A multipart body: the body's fields as form fields, then the files. */
async function formBody(body: unknown, specs: FileSpec[]): Promise<FormData> {
  const form = new FormData();
  if (body && typeof body === "object" && !Array.isArray(body)) {
    for (const [k, v] of Object.entries(body as Row)) {
      if (v !== undefined && v !== null) form.append(k, typeof v === "string" ? v : JSON.stringify(v));
    }
  }
  let total = 0;
  for (const s of specs) {
    const file = await s.load(MAX_UPLOAD_BYTES - total);
    total += file.size;
    form.append(s.field, file);
  }
  return form;
}

/** The session the call carries: owner admin for /api/admin/*, the client's owner for the rest, or none. */
async function sessionFor(d: GrokDeps, path: string, client: ClientRef | null): Promise<string | null> {
  if (path.toLowerCase().startsWith("/api/admin/")) return mintAdminSessionToken(d.env, await ownerAdmin(d.client), TOKEN_SECONDS);
  if (client) return mintSessionToken(d.env, "live", { tenantId: client.id }, TOKEN_SECONDS);
  return null;
}

const softwareRequest: ToolDef<GrokDeps> = {
  name: "software_request",
  description:
    "Any call to the Command Center's own API: every page and button in the app is one of these (software_routes lists them). /api/admin/... runs as the agency owner; any other /api/... runs as the named client's owner, which is their own app. :tenantId in the path is filled from client. JSON body, or files (each from drive_file_id or an http(s) url) to send it as a form upload. Anything but GET is logged before it is sent.",
  inputSchema: {
    type: "object",
    properties: {
      method: { type: "string", enum: [...METHODS], description: "Default GET." },
      path: { type: "string", description: "App path from software_routes, e.g. /api/admin/clients/:tenantId/mission-control." },
      client: { type: "string", description: "Client name or slug. Fills :tenantId; required for the client app's own /api/... routes." },
      query: { type: "object", description: "Query string as name: value." },
      body: { type: "object", description: "JSON body. With files, these become form fields." },
      files: {
        type: "array",
        description: "Files to upload as multipart form data. field defaults to file.",
        items: {
          type: "object",
          properties: { drive_file_id: { type: "string" }, url: { type: "string" }, field: { type: "string" }, name: { type: "string" }, type: { type: "string" } },
        },
      },
      bot: { type: "string", description: "Your name, for the change log." },
    },
    required: ["path"],
  },
  run: async (d, a) => {
    const method = appMethod(a.method);
    const c = text(a.client) ? await findClient(d.client, a.client) : null;
    const path = appPath(a.path, c);
    const url = appUrl(d.origin, path, a.query);
    const specs = fileSpecs(d, a.files);
    const send = async () => {
      const headers: Record<string, string> = { accept: "application/json" };
      const token = await sessionFor(d, path, c);
      if (token) headers.authorization = `Bearer ${token}`;
      let body: BodyInit | undefined;
      if (specs.length) body = await formBody(a.body, specs);
      else if (method !== "GET" && a.body !== undefined && a.body !== null) {
        headers["content-type"] = "application/json";
        body = typeof a.body === "string" ? a.body : JSON.stringify(a.body);
      }
      const res = await fetch(url.href, { method, headers, body, redirect: "manual", signal: AbortSignal.timeout(TIMEOUT_MS) });
      return readAnswer(method, path, res);
    };
    if (method === "GET") return send();
    const payload = {
      bot: botName(a.bot),
      method,
      path,
      query: forLog(a.query),
      body: forLog(a.body),
      ...(specs.length ? { files: specs.map((s) => ({ field: s.field, from: s.from })) } : {}),
    };
    return audited(d.client, "software_request", c?.id ?? null, payload, send);
  },
};

// Past this many matches the answer is cut; a narrower search finds the rest.
const MAX_MATCHES = 30;

const softwareRoutes: ToolDef<GrokDeps> = {
  name: "software_routes",
  description:
    "The map of the Command Center: every API route with its methods. With search (words, all must match), the matching routes with what each does and the body it takes, from the app's own code. :tenantId is a client's id (software_clients, or pass client to software_request).",
  inputSchema: { type: "object", properties: { search: { type: "string", description: "e.g. mission control, creatives, onboarding go live." } }, required: [] },
  run: async (_d, a) => {
    const words = text(a.search).toLowerCase().split(/\s+/).filter(Boolean);
    if (!words.length) return ROUTES.map((r) => `${r.methods.join(",")} ${r.path}`).join("\n");
    const hay = (r: (typeof ROUTES)[number]) => `${r.path} ${r.about}`.toLowerCase().replace(/[-_/]+/g, " ");
    const matches = ROUTES.filter((r) => words.every((w) => hay(r).includes(w.replace(/[-_/]+/g, " "))));
    return JSON.stringify(
      { matches: matches.slice(0, MAX_MATCHES), ...(matches.length > MAX_MATCHES ? { more: matches.length - MAX_MATCHES } : {}) },
      null,
      1,
    );
  },
};

