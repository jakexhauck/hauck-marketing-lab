// Generate .dev.vars (what `wrangler pages dev` reads) from .env.local.
//
// Why: local dev runs the Pages Functions through wrangler, which loads server
// secrets from .dev.vars, NOT .env.local. Rather than hand-maintain a second
// secrets file, derive it: copy the server-side keys and mint a local-only
// SESSION_SECRET so sessions can be signed without touching production's.
//
// Both files are gitignored. Run via `npm run dev:full` (which calls this first)
// or directly with `npm run sync:dev-vars`. Safe to re-run; it preserves an
// existing local SESSION_SECRET so you don't get logged out each restart.

import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import { randomBytes } from "node:crypto";

const APP_DIR = join(dirname(fileURLToPath(import.meta.url)), "..");
const ENV_LOCAL = join(APP_DIR, ".env.local");
const DEV_VARS = join(APP_DIR, ".dev.vars");

// Keys that are frontend-only or local-tooling-only never belong in .dev.vars
// (the Functions runtime). VITE_* is bundled into the browser; the others are
// for migration / Cloudflare scripts, not the running app.
const SKIP_PREFIXES = ["VITE_"];
const SKIP_EXACT = new Set([
  "SUPABASE_ACCESS_TOKEN",
  "CLOUDFLARE_API_TOKEN",
  "CLOUDFLARE_ACCOUNT_ID",
  "PAGES_HOSTNAME",
]);

function parseEnv(text) {
  const out = {};
  for (const line of text.split("\n")) {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith("#")) continue;
    const eq = trimmed.indexOf("=");
    if (eq < 0) continue;
    out[trimmed.slice(0, eq).trim()] = trimmed.slice(eq + 1).trim();
  }
  return out;
}

if (!existsSync(ENV_LOCAL)) {
  console.error("\x1b[31m✗ .env.local not found. Copy .env.example and fill it in.\x1b[0m");
  process.exit(1);
}

const src = parseEnv(readFileSync(ENV_LOCAL, "utf8"));
const existing = existsSync(DEV_VARS) ? parseEnv(readFileSync(DEV_VARS, "utf8")) : {};

const out = {};
for (const [k, v] of Object.entries(src)) {
  if (SKIP_PREFIXES.some((p) => k.startsWith(p))) continue;
  if (SKIP_EXACT.has(k)) continue;
  out[k] = v;
}

// A signing key for local sessions. Keep an existing one so restarts don't
// invalidate the local login; otherwise mint a fresh one. Local-only: never the
// production SESSION_SECRET (that lives in Cloudflare).
out.SESSION_SECRET = existing.SESSION_SECRET || randomBytes(32).toString("hex");

const body =
  "# AUTO-GENERATED by scripts/sync-dev-vars.mjs from .env.local. Do not edit by hand.\n" +
  "# Gitignored. SESSION_SECRET here is local-only, not production's.\n" +
  Object.entries(out)
    .map(([k, v]) => `${k}=${v}`)
    .join("\n") +
  "\n";

writeFileSync(DEV_VARS, body);
console.log(`\x1b[32m✓ Wrote .dev.vars (${Object.keys(out).length} vars).\x1b[0m`);
