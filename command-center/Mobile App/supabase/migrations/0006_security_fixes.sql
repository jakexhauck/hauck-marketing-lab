-- 0006: security and integrity fixes surfaced by the June 2026 audit.
-- Run AFTER 0001..0005. Idempotent: safe to re-run.

-- =========================
-- 1. tenant_users: restore a primary key.
-- 0004 dropped the (tenant_id, user_id) primary key to make user_id nullable
-- and never added a replacement, leaving the table with no PK at all. Add a
-- surrogate identity PK; the two identity-space unique indexes keep handling
-- logical uniqueness.
-- =========================
alter table public.tenant_users
  add column if not exists id bigint generated by default as identity;

do $$
begin
  if not exists (
    select 1 from pg_constraint
    where conrelid = 'public.tenant_users'::regclass
      and contype = 'p'
  ) then
    alter table public.tenant_users add primary key (id);
  end if;
end $$;

-- =========================
-- 2. tenant_users: make the GHL-identity unique index usable by ON CONFLICT.
-- 0004 created it as a partial index (where ghl_user_id is not null), which
-- PostgREST upserts cannot target: ON CONFLICT (tenant_id, ghl_user_id) only
-- infers full indexes, so POST /api/team/sync failed outright. A full unique
-- index behaves identically for rows with a ghl_user_id (NULLs never conflict
-- with each other) and the upsert can infer it.
-- =========================
drop index if exists public.tenant_users_tenant_ghl_uid;

create unique index if not exists tenant_users_tenant_ghl_uid
  on public.tenant_users (tenant_id, ghl_user_id);

-- =========================
-- 3. login_attempts: durable login rate limiting (see functions/lib/ratelimit.ts).
-- Service-role access only: RLS is enabled with no policies, so anon/authed
-- clients can neither read nor write it.
-- =========================
create table if not exists public.login_attempts (
  id         bigint generated by default as identity primary key,
  ip         text not null,
  created_at timestamptz not null default now()
);

create index if not exists login_attempts_ip_time_idx
  on public.login_attempts (ip, created_at desc);

alter table public.login_attempts enable row level security;
